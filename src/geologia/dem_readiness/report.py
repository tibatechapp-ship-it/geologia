"""Auditable, non-ranking DEM coverage/readiness report serialization."""

from datetime import datetime
from enum import StrEnum
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, model_validator

from .coverage import CoverageAssessment
from .models import (
    DeclaredUseContext,
    ReadinessAssessment,
    ReadinessInput,
)
from .readiness import assess_readiness
from .thresholds import FROZEN_V1_THRESHOLDS


NonEmpty = Annotated[str, Field(min_length=1)]


class RepresentativenessStatus(StrEnum):
    UNQUANTIFIED = "unquantified"
    UNDER_EVALUATION = "under_evaluation"
    QUANTITATIVELY_SUPPORTED = "quantitatively_supported"
    NOT_REPRESENTATIVE = "not_representative"


class AnalogueComparisonRecord(BaseModel):
    """A geomorphic comparison hypothesis, explicitly separate from product coverage."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    analogue_region: NonEmpty
    yemen_target_stratum: NonEmpty
    representativeness_status: RepresentativenessStatus
    evidence_reference: str | None = None
    rationale: NonEmpty
    reviewer: NonEmpty
    recorded_at: datetime

    @model_validator(mode="after")
    def require_evidence_for_quantified_status(self) -> "AnalogueComparisonRecord":
        if self.recorded_at.tzinfo is None:
            raise ValueError("recorded_at must be timezone-aware")
        if (
            self.representativeness_status
            in {
                RepresentativenessStatus.QUANTITATIVELY_SUPPORTED,
                RepresentativenessStatus.NOT_REPRESENTATIVE,
            }
            and not self.evidence_reference
        ):
            raise ValueError("quantified representativeness status requires evidence_reference")
        return self


class DEMReadinessReport(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: str = "dem-readiness-report-v1"
    report_id: NonEmpty
    generated_at: datetime
    protocol_version: str
    protocol_implementation_freeze_date: str
    declared_use: DeclaredUseContext
    readiness_input: ReadinessInput
    readiness_assessment: ReadinessAssessment
    coverage_assessments: tuple[CoverageAssessment, ...] = ()
    analogue_comparisons: tuple[AnalogueComparisonRecord, ...] = ()
    accuracy_claim_status: str = "not_generated_by_readiness_report"
    ranking_status: str = "not_generated"
    limitations: tuple[str, ...] = (
        "Coverage gate outcomes describe reference-data sufficiency only, not DEM accuracy.",
        "Analogue geography is not evidence of actual product coverage.",
        "No product ranking or Yemen-wide accuracy claim is generated by this report.",
    )

    @model_validator(mode="after")
    def validate_report_consistency(self) -> "DEMReadinessReport":
        if self.generated_at.tzinfo is None:
            raise ValueError("generated_at must be timezone-aware")
        if self.declared_use != self.readiness_input.declared_use:
            raise ValueError("report declared_use must match readiness_input")
        for assessment in self.coverage_assessments:
            record = assessment.record
            if record.product_version_id != self.declared_use.product_version_id:
                raise ValueError("coverage record product version does not match report scope")
            if record.pilot_area_id != self.declared_use.pilot_area_id:
                raise ValueError("coverage record pilot area does not match report scope")
        if self.accuracy_claim_status != "not_generated_by_readiness_report":
            raise ValueError("readiness report must not claim to generate accuracy results")
        if self.ranking_status != "not_generated":
            raise ValueError("readiness report must not generate a DEM ranking")
        return self


def build_readiness_report(
    *,
    report_id: str,
    generated_at: datetime,
    readiness_input: ReadinessInput,
    coverage_assessments: tuple[CoverageAssessment, ...] = (),
    analogue_comparisons: tuple[AnalogueComparisonRecord, ...] = (),
) -> DEMReadinessReport:
    """Build a report from supplied evidence without fabricating missing results."""
    assessment = assess_readiness(readiness_input)
    return DEMReadinessReport(
        report_id=report_id,
        generated_at=generated_at,
        protocol_version=FROZEN_V1_THRESHOLDS.protocol_version,
        protocol_implementation_freeze_date=(
            FROZEN_V1_THRESHOLDS.implementation_freeze_date
        ),
        declared_use=readiness_input.declared_use,
        readiness_input=readiness_input,
        readiness_assessment=assessment,
        coverage_assessments=coverage_assessments,
        analogue_comparisons=analogue_comparisons,
    )
